#!/usr/bin/env python3
"""Task C8: Negative learning (plan item 28, Wave C FIX BETTER).

Records failed fix shapes per signal into ``eval/fix_blacklist.md``
and steers the next fix prompt away from them.

Interface::

  record_failure(signal, shape, blacklist_path) -> int (new count)
  load_blacklist(blacklist_path) -> {signal: [shapes]}
  shapes_for(signal, source) -> [shapes]  (source: path | dict | None)
  filter_candidates(candidates, signal, source=None) -> [allowed]
  render_blacklist_section(signal, source=None, mention_shapes=True) -> str
  build_fix_prompt(base, signal, candidates=None, source=None,
                   mention_shapes=True) -> str

``signal`` is an eval case id (e.g. ``"uart-tx-div"``); ``shape`` is a
fix-shape name (e.g. ``"reset-missing"``). Both are normalized
(stripped + lowercased) so ``" Reset-Missing "`` and
``"reset-missing"`` blacklist the same row. Re-recording an existing
row bumps its ``(xN)`` count instead of duplicating the bullet.

File format (markdown, human-readable, grep-friendly)::

  # Fix blacklist (negative learning)
  <!-- auto-generated by agent/repair/neglearn.py; do not hand-edit -->
  ## uart-tx-div
  - off-by-one
  - reset-missing (x2)

Signals and shapes render sorted, so repeated records produce
byte-stable diffs. ``load_blacklist`` tolerates junk lines and a
missing file (``{}``, creating nothing).

``build_fix_prompt`` appends the blacklist section (quoting the
avoided shape names by default, so the prompt *includes* the
blacklist) plus an ``Allowed fix shapes:`` line from which
blacklisted shapes are *absent*. With ``mention_shapes=False`` the
blacklisted names appear nowhere in the returned string (strict
negative priming: no failed-shape tokens to anchor on) while the
blacklist is still referenced by name and file.

Default-off contract (Wave C header: additive + default-off): this
module runs ONLY on explicit call. It imports nothing from
agent/loop.py or agent/guard.py, never changes guard verdicts, and no
caller is wired: agent/loop.py, agent/guard.py, eval/score.py and
scripts/ci.sh are untouched.

Pure stdlib (``os``/``re`` only); no API, no keys, no network. File
writes go ONLY to the caller-supplied ``blacklist_path`` -- production
callers pass ``eval/fix_blacklist.md`` (see ``DEFAULT_BLACKLIST_REL``);
tests pass scratch dirs and never touch the real ``eval/`` dir.
"""

import os
import re

DEFAULT_BLACKLIST_REL = os.path.join("eval", "fix_blacklist.md")

_HEADER_LINE = "# Fix blacklist (negative learning)"
_GENERATED_NOTE = ("<!-- auto-generated by agent/repair/neglearn.py; "
                   "do not hand-edit -->")

_SECTION_RE = re.compile(r"^##\s+(?P<signal>.+?)\s*$")
_BULLET_RE = re.compile(r"^-\s+(?P<body>.+?)\s*$")
_COUNT_RE = re.compile(r"^(?P<shape>.+?)\s*\(x(?P<n>\d+)\)\s*$")


def _require_name(value, kind):
    """Normalize a signal/shape name or raise TypeError/ValueError."""
    if kind not in ("signal", "shape"):
        raise ValueError("neglearn: kind must be 'signal' or 'shape', "
                         "got %r" % (kind,))
    if isinstance(value, bool) or not isinstance(value, str):
        raise TypeError("neglearn: %s must be a string, got %r"
                        % (kind, value))
    norm = value.strip().lower()
    if not norm:
        raise ValueError("neglearn: %s must be a non-empty string, got %r"
                         % (kind, value))
    return norm


def _require_path(value):
    """Return the path as str or raise TypeError."""
    if isinstance(value, bool) or not isinstance(value, (str, os.PathLike)):
        raise TypeError("neglearn: blacklist_path must be a path string, "
                        "got %r" % (value,))
    return os.fspath(value)


def _load_counts(blacklist_path):
    """Load {signal: {shape: count}}; missing file -> {} (creates nothing)."""
    path = _require_path(blacklist_path)
    counts = {}
    if not os.path.exists(path):
        return counts
    with open(path, "r", encoding="utf-8") as fh:
        current = None
        for raw in fh:
            line = raw.strip()
            if not line:
                continue
            section = _SECTION_RE.match(line)
            if section:
                try:
                    current = _require_name(section.group("signal"),
                                            "signal")
                except (TypeError, ValueError):
                    current = None
                    continue
                counts.setdefault(current, {})
                continue
            bullet = _BULLET_RE.match(line)
            if bullet is None or current is None:
                continue  # junk line or bullet outside a section: ignore
            body = bullet.group("body").strip()
            numbered = _COUNT_RE.match(body)
            if numbered:
                shape_raw, num = numbered.group("shape"), int(numbered.group("n"))
            else:
                shape_raw, num = body, 1
            try:
                shape = _require_name(shape_raw, "shape")
            except (TypeError, ValueError):
                continue
            if num < 1:
                continue
            counts[current][shape] = max(counts[current].get(shape, 0), num)
    return counts


def _render_counts(counts):
    """Render the counts map to the on-disk markdown format."""
    lines = [_HEADER_LINE, _GENERATED_NOTE]
    for signal in sorted(counts):
        lines.append("## %s" % signal)
        for shape in sorted(counts[signal]):
            num = counts[signal][shape]
            if num > 1:
                lines.append("- %s (x%d)" % (shape, num))
            else:
                lines.append("- %s" % shape)
    return "\n".join(lines) + "\n"


def record_failure(signal, shape, blacklist_path):
    """Record one failed (signal, shape) pair; return its new count.

    Creates the file (and missing parent dirs) on first use; an
    existing row's ``(xN)`` count is bumped instead of duplicated.
    Refuses blank/non-string signals, shapes, or paths.
    """
    name_signal = _require_name(signal, "signal")
    name_shape = _require_name(shape, "shape")
    path = _require_path(blacklist_path)
    counts = _load_counts(path)
    counts.setdefault(name_signal, {})
    counts[name_signal][name_shape] = \
        counts[name_signal].get(name_shape, 0) + 1
    parent = os.path.dirname(os.path.abspath(path))
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(_render_counts(counts))
    return counts[name_signal][name_shape]


def load_blacklist(blacklist_path):
    """Load {signal: [shapes]} with shapes sorted; missing file -> {}."""
    counts = _load_counts(blacklist_path)
    return {signal: sorted(shapes)
            for signal, shapes in sorted(counts.items())}


def _as_shape_list(black):
    """Coerce a loaded-blacklist value to {signal: [shapes]} or raise."""
    if not isinstance(black, dict):
        raise TypeError("neglearn: blacklist dict must map signal -> "
                        "list of shapes, got %r" % (black,))
    return black


def shapes_for(signal, source):
    """Shapes blacklisted for ``signal`` from a path, dict, or None.

    ``source`` is a blacklist file path, a ``load_blacklist`` dict, or
    None (no blacklist -> []). Unknown signals -> [].
    """
    name_signal = _require_name(signal, "signal")
    if source is None:
        return []
    if isinstance(source, dict):
        black = _as_shape_list(source)
    else:
        black = load_blacklist(source)
    found = black.get(name_signal, [])
    if not isinstance(found, (list, tuple)):
        raise TypeError("neglearn: blacklist entry for %r must be a list, "
                        "got %r" % (name_signal, found))
    return list(found)


def filter_candidates(candidates, signal, source=None):
    """Return candidates minus shapes blacklisted for ``signal``.

    Order of the survivors is preserved. Comparison is normalized, so
    ``"Reset-Missing"`` is filtered by a ``"reset-missing"`` row while
    the surviving entries keep their original spelling.
    """
    if not isinstance(candidates, (list, tuple)):
        raise TypeError("neglearn: candidates must be a list/tuple of "
                        "shape names, got %r" % (candidates,))
    blocked = set(shapes_for(signal, source))
    allowed = []
    for entry in candidates:
        norm = _require_name(entry, "shape")
        if norm not in blocked:
            allowed.append(entry)
    return allowed


def render_blacklist_section(signal, source=None, mention_shapes=True):
    """Render the blacklist notice for ``signal`` ("" when empty).

    With ``mention_shapes`` (default) the avoided shape names are
    quoted; otherwise only the count + file reference appear, so no
    blacklisted name occurs in the returned string.
    """
    name_signal = _require_name(signal, "signal")
    shapes = shapes_for(name_signal, source)
    if not shapes:
        return ""
    if mention_shapes:
        return ("Avoid previously failed fix shapes for '%s' "
                "(do NOT retry): %s."
                % (name_signal, ", ".join(shapes)))
    return ("Blacklist: %d previously failed fix shape(s) for '%s' "
            "excluded from candidates (see %s)."
            % (len(shapes), name_signal, DEFAULT_BLACKLIST_REL))


def build_fix_prompt(base_prompt, signal, candidates=None, source=None,
                     mention_shapes=True):
    """Build the next fix prompt steered by the blacklist.

    The result keeps ``base_prompt`` verbatim, appends the blacklist
    section (when the signal has rows), and -- when ``candidates`` is
    given -- appends an ``Allowed fix shapes:`` line from which
    blacklisted shapes are absent.
    """
    if isinstance(base_prompt, bool) or not isinstance(base_prompt, str) \
            or not base_prompt.strip():
        raise TypeError("neglearn: base_prompt must be a non-empty string, "
                        "got %r" % (base_prompt,))
    name_signal = _require_name(signal, "signal")
    parts = [base_prompt.rstrip()]
    section = render_blacklist_section(name_signal, source,
                                       mention_shapes=mention_shapes)
    if section:
        parts.append(section)
    if candidates is not None:
        allowed = filter_candidates(candidates, name_signal, source)
        if allowed:
            parts.append("Allowed fix shapes: %s." % ", ".join(allowed))
        else:
            parts.append("Allowed fix shapes: (none left - "
                         "propose a new shape).")
    return "\n\n".join(parts) + "\n"
