"""Task stranger-2 tests: scorer for the darkriscv stranger entry.

Run: python3 tests/test_stranger2_score.py -v   (from repo root)

Static fixtures only, no model calls, no real sim builds:
- test_registry_*: eval/stranger2.yaml loads to one entry with the
  quarantined ground-truth fix + runnable local_spec pointer.
- test_empty_runs_boards_unrun: no stranger2-* bundles -> UNRUN row
  (unknown fix status, never green, never red).
- test_red/green/triage_*: fixture meta.json bundles board RED /
  GREEN (with time-to-green) / TRIAGE; a later triage never masks an
  earlier decisive GREEN/RED (same rule as eval/score.py).
- test_main_writes_results_md: main() writes the board to a results
  md (path patched to tmp in-test; the repo file is generated by the
  scorer, never hand-edited).
- test_verdict_keyword_convention: static scan (same shape as
  test_spec_run.py) over this task's files -- Verdict is only ever
  built as Verdict(**{"pass": ..., "evidence": ...}) and read via
  getattr(v, "pass"); never positional, never .pass access.
"""
import json
import os
import re
import sys
import tempfile
import tokenize
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from eval import stranger2_score as scorer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THIS_DIR = os.path.dirname(os.path.abspath(__file__))


def _write_meta(run_dir, meta):
    os.makedirs(run_dir, exist_ok=True)
    with open(os.path.join(run_dir, "meta.json"), "w",
              encoding="utf-8") as fh:
        fh.write(json.dumps(meta) + "\n")


class TestRegistry(unittest.TestCase):
    def test_registry_loads_one_entry(self):
        entries = scorer.load_strangers(
            os.path.join(ROOT, "eval", "stranger2.yaml"))
        self.assertEqual(len(entries), 1)
        self.assertEqual(entries[0]["id"], "stranger2")

    def test_registry_names_real_fix_and_proxy(self):
        entries = scorer.load_strangers(
            os.path.join(ROOT, "eval", "stranger2.yaml"))
        entry = entries[0]
        self.assertIn("3dae843", entry.get("ground_truth_fix", ""))
        self.assertEqual(entry.get("local_spec"),
                         "sim/targets/stranger2.yaml")

    def test_registry_missing_file_fails_loud(self):
        with self.assertRaises(OSError):
            scorer.load_strangers(os.path.join(ROOT, "eval", "nope.yaml"))


class TestBoard(unittest.TestCase):
    def _board(self, metas):
        with tempfile.TemporaryDirectory() as tmp:
            for run_id, meta in metas.items():
                _write_meta(os.path.join(tmp, run_id), meta)
            strangers = [{"id": "stranger2", "commit": "3dae843a5740",
                          "manual_baseline_hours": "4"}]
            runs = scorer.load_runs(tmp)
            return scorer.build_board(strangers, runs)

    def test_empty_runs_boards_unrun(self):
        board, green, total = self._board({})
        self.assertIn("UNRUN", board)
        self.assertNotIn("GREEN", board)
        self.assertNotIn("RED", board)
        self.assertEqual((green, total), (0, 1))

    def test_red_bundle_boards_red(self):
        board, green, total = self._board({"stranger2-20261027T000000Z": {
            "case_id": "stranger2", "status": "red", "mode": "live",
            "wall_end_utc": "2026-10-27T00:01:00Z"}})
        self.assertIn("RED", board)
        self.assertNotIn("GREEN", board)
        self.assertEqual((green, total), (0, 1))

    def test_green_bundle_boards_green_with_time(self):
        board, green, total = self._board({"stranger2-20261027T000000Z": {
            "case_id": "stranger2", "status": "green", "mode": "live",
            "wall_end_utc": "2026-10-27T00:02:00Z",
            "time_to_green_s": 64.2, "patch_lines": 1,
            "human_touches": 0}})
        self.assertIn("GREEN", board)
        self.assertIn("64.2", board)
        self.assertEqual((green, total), (1, 1))

    def test_triage_only_gets_triage_row(self):
        board, green, total = self._board({"stranger2-triage": {
            "case_id": "stranger2", "status": "triage", "mode": "triage",
            "wall_end_utc": "2026-10-27T00:01:00Z"}})
        self.assertIn("TRIAGE", board)
        self.assertNotIn("UNRUN", board)
        self.assertEqual((green, total), (0, 1))

    def test_triage_never_masks_decisive_green(self):
        board, green, _total = self._board({
            "stranger2-20261027T000000Z": {
                "case_id": "stranger2", "status": "green", "mode": "live",
                "wall_end_utc": "2026-10-27T00:02:00Z",
                "time_to_green_s": 64.2},
            "stranger2-triage-later": {
                "case_id": "stranger2", "status": "triage",
                "mode": "triage",
                "wall_end_utc": "2026-10-27T00:03:00Z"}})
        self.assertIn("GREEN", board)
        self.assertNotIn("TRIAGE", board)
        self.assertEqual(green, 1)

    def test_non_stranger2_runs_ignored(self):
        board, green, total = self._board({"stranger-jalr-lsb-x": {
            "case_id": "picorv32-fetch-misalign", "status": "green",
            "mode": "live", "wall_end_utc": "2026-10-27T00:02:00Z",
            "time_to_green_s": 64.2}})
        self.assertIn("UNRUN", board)
        self.assertEqual((green, total), (0, 1))


class TestMain(unittest.TestCase):
    def test_main_writes_results_md(self):
        with tempfile.TemporaryDirectory() as tmp:
            _write_meta(os.path.join(tmp, "runs", "stranger2-red1"), {
                "case_id": "stranger2", "status": "red", "mode": "live",
                "wall_end_utc": "2026-10-27T00:01:00Z"})
            arge_path = os.path.join(tmp, "stranger2.yaml")
            with open(os.path.join(ROOT, "eval", "stranger2.yaml"),
                      "r", encoding="utf-8") as fh:
                reg = fh.read()
            with open(arge_path, "w", encoding="utf-8") as fh:
                fh.write(reg)
            old = (scorer.STRANGER_PATH, scorer.RUNS_DIR,
                   scorer.RESULTS_PATH)
            scorer.STRANGER_PATH = arge_path
            scorer.RUNS_DIR = os.path.join(tmp, "runs")
            scorer.RESULTS_PATH = os.path.join(tmp, "stranger2_results.md")
            try:
                self.assertEqual(scorer.main(), 0)
                with open(scorer.RESULTS_PATH, "r",
                          encoding="utf-8") as fh:
                    body = fh.read()
            finally:
                (scorer.STRANGER_PATH, scorer.RUNS_DIR,
                 scorer.RESULTS_PATH) = old
            self.assertIn("stranger2", body)
            self.assertIn("RED", body)


class TestKeywordConvention(unittest.TestCase):
    def test_verdict_keyword_convention(self):
        for name in ("test_stranger2_score.py",
                     "../eval/stranger2_score.py"):
            path = os.path.join(THIS_DIR, name)
            with open(path, "rb") as fh:
                toks = list(tokenize.tokenize(fh.readline))
            code = " ".join(
                t.string
                for t in toks
                if t.type not in (
                    tokenize.COMMENT,
                    tokenize.STRING,
                    tokenize.FSTRING_START,
                    tokenize.FSTRING_MIDDLE,
                    tokenize.FSTRING_END,
                    tokenize.ENCODING,
                    tokenize.NL,
                    tokenize.NEWLINE,
                    tokenize.INDENT,
                    tokenize.DEDENT,
                    tokenize.ENDMARKER,
                )
            )
            self.assertIsNone(
                re.search(r"Verdict\s*\((?!\s*\*)", code),
                f"{name}: positional Verdict(...) construction found",
            )
            self.assertIsNone(
                re.search(r"\.\s*pass\b", code),
                f"{name}: attribute-style .pass access found",
            )


if __name__ == "__main__":
    unittest.main()
